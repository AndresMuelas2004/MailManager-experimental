// Deep-widen the canonical dictionary's literal leaf values to ``string`` so a
// sibling locale (``en.ts``) carries different text while still being forced to
// match es.ts's exact KEY shape — a missing or extra key stays a compile error.
// Typing against a bare ``typeof es`` would, because of ``as const`` above,
// pin every leaf to its Spanish literal and reject every translated string.
type LocaleShape<T> = {
  [K in keyof T]: T[K] extends string ? string : LocaleShape<T[K]>;
};
export type EsDictionary = LocaleShape<typeof es>;
